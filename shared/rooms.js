// ---------- seats ----------

export const seatKey = (seat) => `s${seat}`;

// Array of length room.seats: the uid in each seat, or null if empty.
export function seatList(room) {
  return Array.from({ length: room?.seats || 0 }, (_, i) => room.players?.[seatKey(i)] ?? null);
}
export function playerCount(room) {
  return seatList(room).filter(Boolean).length;
}
export function seatOf(room, uid) {
  const i = seatList(room).indexOf(uid);
  return i < 0 ? null : i;
}
// Next occupied seat after `seat`, wrapping around.
export function nextSeat(room, seat) {
  const list = seatList(room);
  for (let k = 1; k <= list.length; k++) {
    const s = (seat + k) % list.length;
    if (list[s]) return s;
  }
  return seat;
}
// Team for a seat: with `teams` set, seats alternate (2 teams: 0,1,0,1…; 3 teams: 0,1,2,0,1,2).
export function teamOf(room, seat) {
  return room.teams ? seat % room.teams : seat;
}
export function isOnline(room, seat) {
  return !!room.online?.[seatKey(seat)];
}
// Has this seat asked to play again (see playAgain)?
export function wantsAgain(room, seat) {
  return !!room.again?.[seatKey(seat)];
}
// The seat's player name, or "P1", "P2"… when they haven't set one.
export function nameOf(room, seat) {
  return room?.names?.[seatKey(seat)] || `P${seat + 1}`;
}
// Seconds left on the current turn, or null when the room has no timer or no game is on.
export function turnLeft(room, now = Date.now()) {
  if (!room?.turnSecs || room.status !== "playing" || typeof room.turnAt !== "number") return null;
  return Math.max(0, Math.ceil((room.turnAt + room.turnSecs * 1000 - now) / 1000));
}

// A write that changes whose turn it is, the round, or starts the game begins a new turn: note when.
// Games often change the room in place, so the old turn, round and status are noted before fn runs.
function stamped(fn) {
  return (cur) => {
    const was = cur && { turn: cur.turn, round: cur.round, status: cur.status };
    const next = fn(cur);
    if (next && next.status === "playing" && (!was || was.turn !== next.turn || was.round !== next.round || was.status !== "playing")) {
      next.turnAt = Date.now();
    }
    return next;
  };
}

