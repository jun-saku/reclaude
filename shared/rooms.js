// Shared multiplayer rooms for reclaude games: room codes, seats (2–10 players), teams, lobby,
// share links, presence, player names, a turn timer, private per-player data, and four backends.
// Import from a project page with:  import * as rooms from "../shared/rooms.js";
//
// A room is one object at rooms/<CODE> in Firebase Realtime Database:
//   { game, host, seats, min, auto, teams, players: { s0: uid, s1?: uid, … },
//     status: "waiting"|"playing"|"done", turn: <seat>, round, createdAt,
//     board?, winner?: <seat|team> | "draw", line?, last?, left?: <seat>, state?: {…}, online?: { s0?: true, … },
//     again?: { s0?: true, … }, names?: { s0?: "Jun", … }, turnSecs?: <seconds per turn, 0 = no timer>,
//     turnAt?: <ms when the current turn started> }
// Seat keys are "s0".."s9" (not 0..9) so Firebase never turns them into arrays.
// private/<CODE>/s<N> holds one string only that seat's player can read or write (e.g. a hand of cards).
// Access rules: firebase/database.rules.json. Any field a game adds must be allowed there too
// (free-form game data goes in `state`). The rules also enforce who may change what:
//   waiting: the host sets the game up; others may only take an empty seat (filling an auto room starts it).
//            `state` isn't protected yet, so deal hidden or random things in startGame's setup.
//   playing: only the player in seat `turn` may change board/turn/winner/line/last/round/teams/left/state;
//            any seated player may forfeit (quit): status "done", left their own seat, and winner another
//            seat (no teams), the other team (2 teams) or "draw" (3+ players); nothing else changes.
//   done:    the result is fixed; anyone seated may start the next round (round + 1).
//   turn timer: once a turn has run past turnSecs, any seated player may pass it on (skipTurn).
// A taken seat can't be emptied or reassigned, and each player sets only their own online and again flags
// and name (again is cleared when a new round starts). The rules are generated by scripts/rules.mjs.
// Rooms can be deleted by the host while waiting, or by anyone once a day old (createdAt).
//
// Backends all expose:
//   uid, local?, watch(code, cb) → unsubscribe, transact(code, fn) → { committed, value }, removeRoom(code),
//   setAgain(code, seat) (writes only rooms/<code>/again/<seat>: a finished room's other fields are fixed),
//   update(code, fields) (a plain multi-field write; skipTurn and setName use it),
//   watchPrivate(code, seat, cb) → unsubscribe, setPrivate(code, seat, value), clearPrivate(code),
//   presence(code, seat) → stop, online(), offline()
//   topScores(game, n) → [{ uid, name, score }] best first, myScore(game) → entry|null, saveScore(game, name, score)
// transact's fn returns the new room, null to delete it, or undefined to abort. Every backend stamps turnAt
// whenever a write starts a new turn (see stamped), so games don't have to.
// Firebase may call fn with null before it has the room cached: transactions on a room you aren't
// watching (via enter) should return null for a null room, not abort, so Firebase retries with real data.

